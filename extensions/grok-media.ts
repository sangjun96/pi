import { mkdir, open, lstat } from "node:fs/promises";
import { dirname, extname, resolve } from "node:path";
import { withFileMutationQueue, type ExtensionAPI, type ExtensionToolContext } from "@earendil-works/pi-coding-agent";
import { Type } from "typebox";

async function apiKey(ctx: ExtensionToolContext): Promise<string> {
  const key = (await ctx.modelRegistry.getProviderAuth("xai"))?.auth.apiKey?.trim();
  if (!key) throw new Error("xAI API key missing. Use /login xai or set XAI_API_KEY before starting Pi.");
  return key;
}

async function post(path: string, body: object, key: string, signal?: AbortSignal): Promise<Response> {
  const response = await fetch(`https://api.x.ai/v1/${path}`, {
    method: "POST", headers: { Authorization: `Bearer ${key}`, "Content-Type": "application/json" },
    body: JSON.stringify(body), signal,
  });
  if (!response.ok) {
    // Avoid exposing credentials or large provider responses in the transcript.
    throw new Error(`xAI ${path} request failed (HTTP ${response.status}).`);
  }
  return response;
}

async function saveNew(path: string, bytes: Buffer): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  const file = await open(path, "wx");
  try { await file.writeFile(bytes); } finally { await file.close(); }
}

async function assertAvailable(path: string): Promise<void> {
  try { await lstat(path); } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return;
    throw error;
  }
  throw new Error(`Output already exists: ${path}. Choose another path.`);
}

function outputPath(cwd: string, path: string): string {
  if (!path.trim()) throw new Error("Output path cannot be empty.");
  return resolve(cwd, path.startsWith("@") ? path.slice(1) : path);
}

export default function (pi: ExtensionAPI) {
  pi.registerTool({
    name: "grok_image", label: "Grok Image",
    description: "Generate one image with xAI Grok Imagine and save it locally. Paid API; prompt is sent to xAI. Does not overwrite files. Choose a .jpg, .png or .webp output path matching the returned image format.",
    promptSnippet: "Generate an image with Grok and save it to a file",
    parameters: Type.Object({
      prompt: Type.String({ minLength: 1, description: "Image description sent to xAI" }),
      path: Type.String({ minLength: 1, description: "Output file path, normally .jpg; relative to working directory" }),
      aspect_ratio: Type.Optional(Type.String({ description: "e.g. 1:1, 16:9, 9:16, or auto" })),
      resolution: Type.Optional(Type.Union([Type.Literal("1k"), Type.Literal("2k")])),
      quality: Type.Optional(Type.Union([Type.Literal("auto"), Type.Literal("low"), Type.Literal("medium")])),
    }),
    async execute(_id, params, signal, _update, ctx) {
      const path = outputPath(ctx.cwd, params.path);
      if (!params.prompt.trim()) throw new Error("Prompt cannot be empty.");
      if (![".jpg", ".jpeg", ".png", ".webp"].includes(extname(path).toLowerCase())) throw new Error("Use a .jpg, .png or .webp output path.");
      return withFileMutationQueue(path, async () => {
        await assertAvailable(path);
        const key = await apiKey(ctx);
        const response = await post("images/generations", { model: "grok-imagine-image-2.0", prompt: params.prompt, n: 1, response_format: "b64_json", aspect_ratio: params.aspect_ratio, resolution: params.resolution, quality: params.quality }, key, signal);
        const result = await response.json() as { data?: { b64_json?: string }[] };
        const encoded = result.data?.[0]?.b64_json;
        if (!encoded || !/^[A-Za-z0-9+/]+={0,2}$/.test(encoded)) throw new Error("xAI returned no valid image data (possibly filtered).");
        const bytes = Buffer.from(encoded, "base64");
        const format = bytes.subarray(0, 3).equals(Buffer.from([0xff, 0xd8, 0xff])) ? "jpeg" : bytes.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) ? "png" : bytes.toString("ascii", 0, 4) === "RIFF" && bytes.toString("ascii", 8, 12) === "WEBP" ? "webp" : undefined;
        if (!format) throw new Error("xAI returned an unrecognized image format; no file saved.");
        const ext = extname(path).toLowerCase();
        // Preserve the generated bytes even when the provider chooses a different format.
        const actualPath = format === "jpeg" ? (ext === ".jpg" || ext === ".jpeg" ? path : `${path}.jpg`) : (ext === `.${format}` ? path : `${path}.${format}`);
        if (actualPath !== path) await assertAvailable(actualPath);
        signal?.throwIfAborted();
        await saveNew(actualPath, bytes);
        return { content: [{ type: "text", text: `Generated image saved to ${actualPath} (${format}, ${bytes.length} bytes).` }], details: { path: actualPath, format, bytes: bytes.length } };
      });
    },
  });

  pi.registerTool({
    name: "grok_tts", label: "Grok TTS",
    description: "Generate speech from text using xAI TTS and save an MP3 or WAV file. Paid API; text is sent to xAI. Does not overwrite files.",
    promptSnippet: "Generate speech audio with Grok and save it to a file",
    parameters: Type.Object({
      text: Type.String({ minLength: 1, maxLength: 60000, description: "Text to speak; xAI speech tags are supported" }),
      path: Type.String({ minLength: 1, description: "Output .mp3 or .wav path, relative to working directory" }),
      language: Type.Optional(Type.String({ description: "BCP-47 language code such as ko, en, or auto (default auto)" })),
      voice_id: Type.Optional(Type.String({ description: "xAI voice ID, e.g. eve or ara (default eve); custom IDs supported" })),
      speed: Type.Optional(Type.Number({ minimum: 0.7, maximum: 1.5 })),
    }),
    async execute(_id, params, signal, _update, ctx) {
      const path = outputPath(ctx.cwd, params.path);
      if (!params.text.trim() || Array.from(params.text).length > 60000) throw new Error("Text must contain 1–60,000 characters.");
      const ext = extname(path).toLowerCase();
      if (ext !== ".mp3" && ext !== ".wav") throw new Error("Output path must end in .mp3 or .wav.");
      return withFileMutationQueue(path, async () => {
        await assertAvailable(path);
        const key = await apiKey(ctx);
        const response = await post("tts", { text: params.text, language: params.language || "auto", voice_id: params.voice_id || "eve", speed: params.speed, output_format: { codec: ext.slice(1) } }, key, signal);
        const bytes = Buffer.from(await response.arrayBuffer());
        if (!bytes.length) throw new Error("xAI returned empty audio.");
        signal?.throwIfAborted();
        await saveNew(path, bytes);
        return { content: [{ type: "text", text: `Generated speech saved to ${path} (${bytes.length} bytes).` }], details: { path, bytes: bytes.length } };
      });
    },
  });
}
